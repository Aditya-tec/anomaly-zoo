// Generates app/grid-classes.css: the timeline's grid placement as classes, so
// no element needs an inline style attribute and the CSP can drop
// style-src 'unsafe-inline' (spec 10.3). Rows: an event has at most two
// timeline entries per scheduled step (the first attempt and the resumed or
// skipped one) and a schedule has at most 200 steps, so 400 rows; 512 leaves room.
//   node scripts/gen-grid-css.mjs          write the file
//   node scripts/gen-grid-css.mjs --check  fail if the committed file is stale
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const MAX_COLS = 6;
export const MAX_ROWS = 512;

const lines = ["/* Generated by scripts/gen-grid-css.mjs. Do not edit. */"];
for (let c = 1; c <= MAX_COLS; c++) lines.push(`.gcols-${c} { grid-template-columns: repeat(${c}, minmax(0, 1fr)); }`);
for (let c = 1; c <= MAX_COLS; c++) lines.push(`.gc-${c} { grid-column: ${c}; }`);
for (let r = 1; r <= MAX_ROWS; r++) lines.push(`.gr-${r} { grid-row: ${r}; }`);
// A lane runs from the first row to the row after the last event.
for (let r = 2; r <= MAX_ROWS + 2; r++) lines.push(`.glane-${r} { grid-row: 1 / ${r}; }`);
for (let t = 1; t <= 6; t++) lines.push(`[data-txn="T${t}"] { --txn: var(--txn-${t}); }`);
lines.push(".txn-ink { color: var(--txn); }");
const css = lines.join("\n") + "\n";

const target = join(process.cwd(), "app", "grid-classes.css");
if (process.argv.includes("--check")) {
  const have = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (have !== css) {
    console.error("app/grid-classes.css is stale: run `node scripts/gen-grid-css.mjs`");
    process.exit(1);
  }
  console.log("app/grid-classes.css is current");
} else {
  writeFileSync(target, css);
  console.log(`wrote app/grid-classes.css (${css.length} bytes)`);
}
