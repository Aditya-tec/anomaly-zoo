// Generates THIRD_PARTY_NOTICES.md from the lockfile, the installed packages and
// the Go module cache. Run from the repository root after `npm ci` in web/:
//   node scripts/gen-third-party-notices.mjs          write the file
//   node scripts/gen-third-party-notices.mjs --check  fail if the committed file is stale
// Nothing is typed by hand except the fixed sentences below.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const out = join(root, "THIRD_PARTY_NOTICES.md");
const lock = JSON.parse(readFileSync(join(root, "web", "package-lock.json"), "utf8"));
const engine = JSON.parse(readFileSync(join(root, "web", "public", "engine", "engine.json"), "utf8"));

function licenseOf(name, fallback) {
  const p = join(root, "web", "node_modules", name, "package.json");
  if (existsSync(p)) {
    const j = JSON.parse(readFileSync(p, "utf8"));
    const l = typeof j.license === "string" ? j.license : j.license?.type ?? (j.licenses ?? []).map((x) => x.type).join(" OR ");
    if (l) return l;
  }
  return fallback ?? "UNKNOWN";
}

// ---- npm: the production closure (what `npm ci --omit=dev` installs) ----
const npmRows = [];
for (const [k, v] of Object.entries(lock.packages)) {
  if (!k || v.dev) continue;
  const name = k.replace(/^.*node_modules\//, "");
  npmRows.push({ name, version: v.version, license: licenseOf(name, v.license), optional: Boolean(v.optional) });
}
npmRows.sort((a, b) => a.name.localeCompare(b.name));
const direct = new Set(Object.keys(JSON.parse(readFileSync(join(root, "web", "package.json"), "utf8")).dependencies));

// ---- Go: modules of the conformance harness, and the toolchain behind the WASM ----
function sh(dir, ...args) {
  return execFileSync(args[0], args.slice(1), { cwd: dir, encoding: "utf8" });
}
const confDir = join(root, "conformance");
const seen = new Map();
for (const line of sh(confDir, "go", "list", "-deps", "-f", "{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}", "./...").split(String.fromCharCode(10))) {
  const [path, version, Dir] = line.trim().split("|");
  if (!path || !Dir || path === "github.com/Aditya-tec/anomaly-zoo" || path === "github.com/Aditya-tec/anomaly-zoo/conformance") continue;
  seen.set(path, { Path: path, Version: version, Dir });
}
const mods = [...seen.values()];
function goLicense(dir) {
  for (const f of ["LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING"]) {
    const p = join(dir, f);
    if (!existsSync(p)) continue;
    const t = readFileSync(p, "utf8");
    const copyright = (t.match(/^Copyright .*$/m) ?? [""])[0].trim();
    const kind = /Permission is hereby granted, free of charge/.test(t) ? "MIT" : /Redistribution and use in source and binary forms/.test(t) ? "BSD-3-Clause" : "see LICENSE";
    return { kind, copyright, text: t.trim() };
  }
  return { kind: "UNKNOWN", copyright: "", text: "" };
}
const goRows = mods.map((m) => ({ path: m.Path, version: m.Version, ...goLicense(m.Dir) })).sort((a, b) => a.path.localeCompare(b.path));
const goroot = sh(root, "go", "env", "GOROOT").trim();
const goLic = goLicense(goroot);

const lines = [];
lines.push("# Third-party notices", "");
lines.push("Anomaly Zoo itself is MIT licensed (see `LICENSE`). This file lists the third-party code it ships or builds with, with exact versions and licenses. It is generated by `scripts/gen-third-party-notices.mjs` from `web/package-lock.json`, the installed packages and the Go module cache; CI fails if it is stale. Do not edit it by hand.", "");
lines.push("## What reaches a visitor's browser", "");
lines.push("* The static pages are built by Next.js from React components; the browser receives the compiled application bundle, which contains code from **next**, **react** and **react-dom** (their exact versions are in the table below) and from the project's own source.");
lines.push(`* The calculation engine is the project's own Go code compiled to WebAssembly with the Go toolchain **${engine.goVersion}**. The WebAssembly module therefore contains the Go runtime and standard library, which are ${goLic.kind} licensed, and the page loads \`wasm_exec.js\` from the same toolchain (also ${goLic.kind}).`);
lines.push("* **Fonts:** none are shipped. The site uses system font stacks, so there are no font files to attribute.", "");
lines.push("## npm packages (production dependency closure)", "");
lines.push("The table is everything `npm ci --omit=dev` installs for `web/`. Of these, only the code the bundler pulls into the application bundle is served to visitors; the rest is used while building, or is an optional per-platform binary (marked *optional*) that is installed only on the matching operating system and is never served. Dev dependencies (test and lint tools) are not shipped and are not listed.", "");
lines.push("| Package | Version | License | Note |", "|---|---|---|---|");
for (const r of npmRows) lines.push(`| ${r.name} | ${r.version} | ${r.license} | ${direct.has(r.name) ? "direct dependency" : r.optional ? "optional" : "transitive"} |`);
lines.push("");
lines.push("## Go: conformance harness (`conformance/`, not shipped to visitors)", "");
lines.push("The conformance harness is a separate Go module used in CI to compare the engine with PostgreSQL. It depends on:", "");
lines.push("| Module | Version | License | Copyright |", "|---|---|---|---|");
for (const r of goRows) lines.push(`| ${r.path} | ${r.version} | ${r.kind} | ${r.copyright} |`);
lines.push("");
lines.push("## Go toolchain and standard library", "");
lines.push(`Go ${engine.goVersion}: ${goLic.copyright} Licensed under the ${goLic.kind} license:`, "");
lines.push("```", goLic.text, "```", "");
lines.push("## Full license texts of the Go modules", "");
for (const r of goRows) {
  lines.push(`### ${r.path} ${r.version} (${r.kind})`, "", "```", r.text, "```", "");
}
const doc = lines.join("\n").replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  const have = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (have !== doc) {
    console.error("THIRD_PARTY_NOTICES.md is stale: run `node scripts/gen-third-party-notices.mjs` and commit the result");
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is current (${npmRows.length} npm packages, ${goRows.length} Go modules)`);
} else {
  writeFileSync(out, doc);
  console.log(`wrote THIRD_PARTY_NOTICES.md (${npmRows.length} npm packages, ${goRows.length} Go modules)`);
}
